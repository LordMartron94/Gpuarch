package main

import (
	"fmt"
	"foundation/system"
	"os/exec"
	"strings"
	"time"
)

const (
	resultNamesFile           = "result_names_gen.go"
	vulkanResultGeneratorTool = "gpuarch Vulkan bindings generator"
	vulkanResultEnumName      = "VkResult"
)

func generateResultContent(enums []VulkanSpecIREnum, resultDir string) error {
	var vkResult *VulkanSpecIREnum
	for i := range enums {
		if enums[i].Name == vulkanResultEnumName {
			vkResult = &enums[i]
			break
		}
	}
	if vkResult == nil {
		return fmt.Errorf("generate result: %s enum not found in spec IR", vulkanResultEnumName)
	}

	seenValues := make(map[string]string)
	for _, value := range vkResult.Values {
		if value.Key == "" || value.Value == "" {
			continue
		}
		if _, exists := seenValues[value.Value]; exists {
			continue
		}
		seenValues[value.Value] = value.Key
	}

	var body strings.Builder
	body.WriteString("func vulkanResultNameLookup(result bindings.VkResult) (string, bool) {\n")
	body.WriteString("\tswitch result {\n")
	for _, name := range seenValues {
		fmt.Fprintf(&body, "\tcase bindings.%s:\n\t\treturn \"%s\", true\n", name, name)
	}
	body.WriteString("\t}\n")
	body.WriteString("\treturn \"\", false\n")
	body.WriteString("}\n")

	content := fmt.Sprintf(
		"// This file was auto-generated by '%s' at %s\n\npackage result\n\nimport \"gpuarch/vulkan/bindings\"\n\n%s",
		vulkanResultGeneratorTool,
		time.Now().Format("2006-01-02 15:04:05 MST"),
		body.String(),
	)

	outputPath := system.PathJoin(resultDir, resultNamesFile)
	if err := system.FileWriteString(outputPath, content); err != nil {
		return fmt.Errorf("write %s to %s: %w", resultNamesFile, outputPath, err)
	}

	return vulkanResultFormat(resultDir)
}

func vulkanResultFormat(resultDir string) error {
	cmd := exec.Command("gofmt", "-w", resultDir)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("gofmt %s: %w\n%s", resultDir, err, output)
	}
	return nil
}
